export type TKey = keyof typeof cs;
const DICT: Record<Lang, Record<TKey, string>> = { cs, en };
const STORAGE_KEY = "wakeword-trainer.lang";

export function detectLanguage(): Lang {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === "cs" || stored === "en") return stored;
  } catch {
    /* ignore */
  }
  const prefs = navigator.languages?.length ? navigator.languages : [navigator.language];
  for (const l of prefs) {
    const code = (l || "").toLowerCase();
    if (code.startsWith("cs") || code.startsWith("sk")) return "cs";
    if (code.startsWith("en")) return "en";
  }
  return "en";
}

export function format(template: string, params?: Params): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, k: string) => (params[k] === undefined ? `{${k}}` : String(params[k])));
}

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (key: TKey, params?: Params) => string };
const I18nContext = createContext<Ctx>({ lang: "en", setLang: () => undefined, t: (k) => k });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => detectLanguage());
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch {
      /* ignore */
    }
  }, []);
  const t = useCallback((key: TKey, params?: Params) => format(DICT[lang][key] ?? DICT.en[key] ?? key, params), [lang]);
  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}

/** Translates a backend error payload ({code, message} or plain string). */
export function errorText(t: Ctx["t"], err: unknown): string {
  if (err && typeof err === "object" && "code" in err) {
    const code = String((err as { code: string }).code);
    const key = `err.${code}` as TKey;
    if (key in cs) return t(key);
    return String((err as { message?: string }).message ?? code);
  }
  if (err instanceof Error) return err.message;
  return String(err);
}
